/**
 * Scope a Next.js app's globals.css so two design systems (storefront + merchant portal)
 * can live in one page. Tailwind/base imports are dropped (the shell imports them once);
 * everything else is nested under `html.<scopeClass>` — `:root` and `body` become the scope
 * itself, so the theme switches by toggling one class on <html>.
 *
 *   node build/scope-css.mjs <in.css> <out.css> <scopeClass>
 */
import { readFileSync, writeFileSync } from 'node:fs';

const [, , input, output, scopeClass] = process.argv;
if (!input || !output || !scopeClass) {
  console.error('usage: scope-css.mjs <in.css> <out.css> <scopeClass>');
  process.exit(2);
}

const source = readFileSync(input, 'utf8');
const kept = source
  .split('\n')
  .filter((line) => !/^\s*@(import|source|plugin|config)\b/.test(line))
  .join('\n');

// `:root { … }` → `html.scope { … }`; `body { … }` → `html.scope body { … }`; every other
// top-level selector is nested under the scope. Implemented as one nesting block so the
// output stays valid regardless of how the app formats its CSS.
const scoped = kept
  .replace(/(^|\n)\s*:root\s*\{/g, '$1&, &:root {')
  .replace(/(^|\n)\s*body\s*\{/g, '$1& body {');

const banner = `/* Generated by browser-demo/build/scope-css.mjs from ${input.split('/').slice(-3).join('/')} — do not edit. */\n`;
writeFileSync(output, `${banner}html.${scopeClass} {\n${scoped}\n}\n`);
console.log(`scoped ${input} → ${output} (html.${scopeClass})`);
